-- 08_integracao_persistencia.sql
-- Migração idempotente para bancos já existentes: adiciona apenas colunas e
-- tabelas novas, sem apagar ou reescrever dados. Pode rodar em todo startup.
-- Aplicada depois de 01, 02, 04 e 07.

-- Perfil do administrador (função/cargo exibido no painel).
ALTER TABLE usuario
    ADD COLUMN IF NOT EXISTS funcao VARCHAR(100);

-- Perfil do artesão: o que antes era estático/em memória passa a persistir.
ALTER TABLE loja
    ADD COLUMN IF NOT EXISTS regiao VARCHAR(150),
    ADD COLUMN IF NOT EXISTS foto TEXT,
    ADD COLUMN IF NOT EXISTS foto_capa TEXT,
    ADD COLUMN IF NOT EXISTS redes_sociais VARCHAR(200),
    ADD COLUMN IF NOT EXISTS tecnicas JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS certificacoes JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS dados_bancarios VARCHAR(300),
    ADD COLUMN IF NOT EXISTS configuracao_envio JSONB;

-- Curadoria de origem durável. Produtos antigos seguem aprovados para não
-- desaparecerem do catálogo; novos produtos nascem PENDENTE pela aplicação.
ALTER TABLE produto
    ADD COLUMN IF NOT EXISTS status_validacao VARCHAR(20) NOT NULL DEFAULT 'APROVADA',
    ADD COLUMN IF NOT EXISTS selo_ativo BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS justificativa_validacao TEXT,
    ADD COLUMN IF NOT EXISTS enviado_em TIMESTAMP,
    ADD COLUMN IF NOT EXISTS decidido_em TIMESTAMP;

ALTER TABLE produto ADD COLUMN IF NOT EXISTS decidido_por_id INTEGER REFERENCES usuario(id_usuario);

-- Detalhes técnicos, origem estendida e SKU do produto (alinhados a schema.prisma).
ALTER TABLE produto
    ADD COLUMN IF NOT EXISTS sku TEXT,
    ADD COLUMN IF NOT EXISTS material TEXT,
    ADD COLUMN IF NOT EXISTS dimensoes TEXT,
    ADD COLUMN IF NOT EXISTS peso NUMERIC(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS certificado TEXT,
    ADD COLUMN IF NOT EXISTS informacoes_origem TEXT,
    ADD COLUMN IF NOT EXISTS prazo_producao_dias INTEGER,
    ADD COLUMN IF NOT EXISTS capacidade_producao INTEGER;

UPDATE produto SET peso = 0 WHERE peso IS NULL;
ALTER TABLE produto ALTER COLUMN peso SET DEFAULT 0;
ALTER TABLE produto ALTER COLUMN peso SET NOT NULL;

-- Moderação de avaliações durável.
ALTER TABLE avaliacao
    ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'PUBLICADO',
    ADD COLUMN IF NOT EXISTS motivo VARCHAR(50),
    ADD COLUMN IF NOT EXISTS sinalizada_em TIMESTAMP,
    ADD COLUMN IF NOT EXISTS moderada_em TIMESTAMP;

-- Frete confirmado pelo servidor no checkout.
ALTER TABLE pedido
    ADD COLUMN IF NOT EXISTS valor_frete NUMERIC(10,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS recuperacao_senha (
    id_recuperacao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fk_usuario_id_usuario INTEGER NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    usado_em TIMESTAMP,
    criado_em TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_recuperacao_senha PRIMARY KEY (id_recuperacao),
    CONSTRAINT uq_recuperacao_token UNIQUE (token_hash),
    CONSTRAINT fk_recuperacao_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_recuperacao_usuario
    ON recuperacao_senha (fk_usuario_id_usuario);

CREATE TABLE IF NOT EXISTS ticket (
    id_ticket INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fk_usuario_id_usuario INTEGER NOT NULL,
    assunto VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'TRIAGEM_INTELIGENTE',
    prioridade VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    categoria VARCHAR(30),
    criado_em TIMESTAMP NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_ticket PRIMARY KEY (id_ticket),
    CONSTRAINT fk_ticket_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_ticket_usuario
    ON ticket (fk_usuario_id_usuario);

CREATE TABLE IF NOT EXISTS ticket_mensagem (
    id_mensagem INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fk_ticket_id_ticket INTEGER NOT NULL,
    autor VARCHAR(20) NOT NULL,
    texto TEXT NOT NULL,
    categoria VARCHAR(30),
    sugestoes JSONB NOT NULL DEFAULT '[]'::jsonb,
    criado_em TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_ticket_mensagem PRIMARY KEY (id_mensagem),
    CONSTRAINT fk_ticket_mensagem_ticket
        FOREIGN KEY (fk_ticket_id_ticket)
        REFERENCES ticket (id_ticket) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ticket_mensagem_ticket
    ON ticket_mensagem (fk_ticket_id_ticket);

CREATE TABLE IF NOT EXISTS personalizacao (
    id_personalizacao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fk_usuario_id_usuario INTEGER NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,
    cor VARCHAR(100),
    tamanho VARCHAR(100),
    inscricao VARCHAR(200),
    detalhes TEXT,
    mensagem TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ENVIADA',
    prazo_adicional_dias INTEGER NOT NULL DEFAULT 0,
    preco_adicional NUMERIC(10,2) NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_personalizacao PRIMARY KEY (id_personalizacao),
    CONSTRAINT fk_personalizacao_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_personalizacao_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto)
);

CREATE INDEX IF NOT EXISTS idx_personalizacao_usuario
    ON personalizacao (fk_usuario_id_usuario);
CREATE INDEX IF NOT EXISTS idx_personalizacao_produto
    ON personalizacao (fk_produto_id_produto);

-- Idempotência de eventos de pagamento (RN38) e motivo de recusa/expiração (RN33).
ALTER TABLE pagamento
    ADD COLUMN IF NOT EXISTS chave_idempotencia VARCHAR(120),
    ADD COLUMN IF NOT EXISTS motivo TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_pagamento_chave_idempotencia
    ON pagamento (chave_idempotencia)
    WHERE chave_idempotencia IS NOT NULL;

-- Registro persistido de tentativas de login para bloqueio temporário (HU-01 / TC11).
CREATE TABLE IF NOT EXISTS tentativa_login (
    email VARCHAR(254) PRIMARY KEY,
    tentativas INTEGER NOT NULL DEFAULT 0,
    bloqueado_ate TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Suspensão e reativação de cadastro pelo administrador (HU-16 / TC24, issue #39).
-- A situação fica no usuário, para o login ler sem junção. Cada ação fica na tabela de
-- auditoria, com responsável, justificativa, resultado e data: reativar não apaga o
-- registro da suspensão. A restrição vai junto do ADD COLUMN para o script seguir idempotente.
ALTER TABLE usuario
    ADD COLUMN IF NOT EXISTS situacao VARCHAR(20) NOT NULL DEFAULT 'ATIVO'
        CONSTRAINT ck_usuario_situacao CHECK (situacao IN ('ATIVO', 'SUSPENSO'));

CREATE TABLE IF NOT EXISTS acao_administrativa_usuario (
    id_acao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fk_usuario_alvo INTEGER NOT NULL,
    fk_usuario_responsavel INTEGER NOT NULL,
    acao VARCHAR(20) NOT NULL,
    justificativa TEXT NOT NULL,
    situacao_resultante VARCHAR(20) NOT NULL,
    realizada_em TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_acao_administrativa_usuario PRIMARY KEY (id_acao),
    CONSTRAINT fk_acao_usuario_alvo
        FOREIGN KEY (fk_usuario_alvo)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_acao_usuario_responsavel
        FOREIGN KEY (fk_usuario_responsavel)
        REFERENCES usuario (id_usuario),
    CONSTRAINT ck_acao_administrativa_acao CHECK (acao IN ('SUSPENDER', 'REATIVAR')),
    CONSTRAINT ck_acao_administrativa_situacao CHECK (situacao_resultante IN ('ATIVO', 'SUSPENSO'))
);

CREATE INDEX IF NOT EXISTS idx_acao_usuario_alvo
    ON acao_administrativa_usuario (fk_usuario_alvo);
