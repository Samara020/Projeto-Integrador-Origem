BEGIN;

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(20),
    usuario_tipo VARCHAR(20) NOT NULL,

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,

    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria)
);

CREATE TABLE loja (
    id_loja INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    fk_usuario_id_usuario INTEGER NOT NULL,

    CONSTRAINT pk_loja PRIMARY KEY (id_loja),
    CONSTRAINT fk_loja_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario)
);

CREATE TABLE endereco_de_entrega (
    id_endereco INTEGER GENERATED BY DEFAULT AS IDENTITY,
    logradouro VARCHAR(200) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    cpf CHAR(11) NOT NULL CHECK (cpf ~ '^[0-9]{11}$'),

    CONSTRAINT pk_endereco_de_entrega
        PRIMARY KEY (id_endereco)
);

CREATE TABLE produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    tecnica VARCHAR(100) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    origem VARCHAR(150) NOT NULL,
    modalidade_producao VARCHAR(30) NOT NULL,
    peca_unica BOOLEAN NOT NULL,
    fk_loja_id_loja INTEGER NOT NULL,
    fk_categoria_id_categoria INTEGER NOT NULL,

    CONSTRAINT pk_produto PRIMARY KEY (id_produto),
    CONSTRAINT ck_produto_preco
        CHECK (preco >= 0),
    CONSTRAINT fk_produto_loja
        FOREIGN KEY (fk_loja_id_loja)
        REFERENCES loja (id_loja),
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (fk_categoria_id_categoria)
        REFERENCES categoria (id_categoria)
);

CREATE TABLE estoque (
    id_estoque INTEGER GENERATED BY DEFAULT AS IDENTITY,
    quantidade_disponivel INTEGER NOT NULL,
    ponto_reposicao INTEGER NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,

    CONSTRAINT pk_estoque PRIMARY KEY (id_estoque),
    CONSTRAINT ck_estoque_quantidade
        CHECK (quantidade_disponivel >= 0),
    CONSTRAINT ck_estoque_reposicao
        CHECK (ponto_reposicao >= 0),
    CONSTRAINT uq_estoque_produto
        UNIQUE (fk_produto_id_produto),
    CONSTRAINT fk_estoque_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto)
);

CREATE TABLE imagem (
    id_imagem INTEGER GENERATED BY DEFAULT AS IDENTITY,
    url TEXT NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,

    CONSTRAINT pk_imagem PRIMARY KEY (id_imagem),
    CONSTRAINT fk_imagem_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto)
);

CREATE TABLE carrinho (
    id_carrinho INTEGER GENERATED BY DEFAULT AS IDENTITY,
    status VARCHAR(30) NOT NULL,
    data_criacao TIMESTAMP NOT NULL,
    fk_usuario_id_usuario INTEGER NOT NULL,

    CONSTRAINT pk_carrinho PRIMARY KEY (id_carrinho),
    CONSTRAINT uq_carrinho_usuario
        UNIQUE (fk_usuario_id_usuario),
    CONSTRAINT fk_carrinho_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario)
);

CREATE TABLE item_carrinho (
    numero_item INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,
    fk_carrinho_id_carrinho INTEGER NOT NULL,

    CONSTRAINT pk_item_carrinho
        PRIMARY KEY (fk_carrinho_id_carrinho, numero_item),
    CONSTRAINT ck_item_carrinho_quantidade
        CHECK (quantidade > 0),
    CONSTRAINT ck_item_carrinho_preco
        CHECK (preco_unitario >= 0),
    CONSTRAINT fk_item_carrinho_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto),
    CONSTRAINT fk_item_carrinho_carrinho
        FOREIGN KEY (fk_carrinho_id_carrinho)
        REFERENCES carrinho (id_carrinho)
);

CREATE TABLE pedido (
    id_pedidos INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL,
    fk_usuario_id_usuario INTEGER NOT NULL,
    fk_endereco_de_entrega_id_endereco INTEGER NOT NULL,

    CONSTRAINT pk_pedido PRIMARY KEY (id_pedidos),
    CONSTRAINT fk_pedido_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_pedido_endereco
        FOREIGN KEY (fk_endereco_de_entrega_id_endereco)
        REFERENCES endereco_de_entrega (id_endereco)
);

CREATE TABLE item_pedido (
    numero_item INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    quantidade INTEGER NOT NULL,
    fk_pedido_id_pedidos INTEGER NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,

    CONSTRAINT pk_item_pedido
        PRIMARY KEY (fk_pedido_id_pedidos, numero_item),
    CONSTRAINT ck_item_pedido_preco
        CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_pedido_subtotal
        CHECK (subtotal = preco_unitario * quantidade),
    CONSTRAINT ck_item_pedido_quantidade
        CHECK (quantidade > 0),
    CONSTRAINT fk_item_pedido_pedido
        FOREIGN KEY (fk_pedido_id_pedidos)
        REFERENCES pedido (id_pedidos),
    CONSTRAINT fk_item_pedido_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto)
);

CREATE TABLE pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data TIMESTAMP NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    forma_pagamento VARCHAR(30) NOT NULL,
    fk_pedido_id_pedidos INTEGER NOT NULL,

    CONSTRAINT pk_pagamento PRIMARY KEY (id_pagamento),
    CONSTRAINT ck_pagamento_valor
        CHECK (valor >= 0),
    CONSTRAINT fk_pagamento_pedido
        FOREIGN KEY (fk_pedido_id_pedidos)
        REFERENCES pedido (id_pedidos)
);

CREATE TABLE avaliacao (
    id_avaliacao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nota SMALLINT NOT NULL,
    comentario TEXT,
    data_avaliacao TIMESTAMP NOT NULL,
    fk_usuario_id_usuario INTEGER NOT NULL,
    fk_produto_id_produto INTEGER NOT NULL,

    CONSTRAINT pk_avaliacao PRIMARY KEY (id_avaliacao),
    CONSTRAINT ck_avaliacao_nota
        CHECK (nota BETWEEN 1 AND 5),
    CONSTRAINT fk_avaliacao_usuario
        FOREIGN KEY (fk_usuario_id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_avaliacao_produto
        FOREIGN KEY (fk_produto_id_produto)
        REFERENCES produto (id_produto)
);

CREATE TABLE historico_pedido (
    id_historico INTEGER GENERATED BY DEFAULT AS IDENTITY,
    status VARCHAR(30) NOT NULL,
    observacao TEXT,
    data TIMESTAMP NOT NULL,
    fk_pedido_id_pedidos INTEGER NOT NULL,

    CONSTRAINT pk_historico_pedido
        PRIMARY KEY (id_historico),
    CONSTRAINT fk_historico_pedido
        FOREIGN KEY (fk_pedido_id_pedidos)
        REFERENCES pedido (id_pedidos)
);

COMMIT;

